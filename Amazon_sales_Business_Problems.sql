/*
Q12: Product Profit Margin
Problem: Calculate profit margin percentage for each product using RANK window function.
*/
SELECT 
    product_id,
    product_name,
    price,
    cogs,
    (price - cogs) AS profit,
    ROUND(((price - cogs) / price) * 100, 2) AS profit_margin_percentage,
    RANK() OVER (ORDER BY ((price - cogs) / price) DESC) AS margin_rank
FROM products
WHERE price > 0
ORDER BY profit_margin_percentage DESC;



