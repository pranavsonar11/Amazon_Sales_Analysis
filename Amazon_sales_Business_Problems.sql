/*
1. Top Selling Products
Query the top 10 products by total sales value.
Challenge: Include product name, total quantity sold, and total sales value.
*/
select sub.product_id , p.product_name, sub.tot_qty, sub.tot_sales 
From (	
	select product_id, sum(quantity) tot_qty , round(sum(total_sales)) as tot_sales
	from order_items
	group by product_id
	order by tot_Sales desc
	limit 10 ) sub
join products p
on sub.product_id = p.product_id;


/*
2. Revenue by Category
Calculate total revenue generated by each product category.
Challenge: Include the percentage contribution of each category to total revenue.
*/

select  c.category_id, c.category_name,
		round(sum(ot.total_sales)) as total_sales,
        round(sum(ot.total_sales)*100.0/(select sum(total_sales) from order_items),2) as perc_contri
from order_items ot
join products p
on ot.product_id = p.product_id
join categories c
on p.category_id = c.category_id
group by c.category_id, c.category_name
order by perc_contri desc;


/*
3. Average Order Value (AOV)
Compute the average order value for each customer.
Challenge: Include only customers with more than 5 orders.
*/
select  o.customer_id,
		concat (c.first_name , ' ', c.last_name) as fname,
		round(sum(ot.total_sales)/count(o.customer_id),2) as AOV,
        count(o.customer_id) as cnt_orders
from order_items ot
join orders o
on ot.order_id = o.order_id
join customers c
on o.customer_id = c.customer_id
group by o.customer_id, concat (c.first_name , ' ', c.last_name)
having count(o.customer_id) > 5
order by AOV desc ;
/*
4. Monthly Sales Trend
Query monthly total sales over the past year.
Challenge: Display the sales trend, grouping by month, return current_month sale, last month sale!
*/
with cte as(
select  extract(month from o.order_date) as month,
		monthname(o.order_date) as month_name,
		round(sum(total_sales)) as curr_month_sale
from order_items ot
join orders o
on ot.order_id = o.order_id
group by extract(month from o.order_date) , monthname(o.order_date) 
order by month asc ) ,

cte2 as( 
select *,
		lag(curr_month_sale) over() as prev_month_sale
from cte )  

SELECT
    month,
    month_name,
    curr_month_sale,
    prev_month_sale,
    (curr_month_sale - prev_month_sale) AS mom_change,
    ROUND((curr_month_sale - prev_month_sale) * 100.0 / prev_month_sale, 2) AS mom_percentage_change
FROM cte2
ORDER BY month;

