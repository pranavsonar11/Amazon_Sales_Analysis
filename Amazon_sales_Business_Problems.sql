/*
15. Inactive Sellers
Identify sellers who haven't made any sales in the last 6 months.
Challenge: Show the last sale date and total sales from those sellers.

*/

WITH seller_sales AS (
    SELECT 
        seller_id,
        MAX(order_date) AS last_sale_date,
        COUNT(order_id) AS total_sales
    FROM orders
    GROUP BY seller_id
),
cutoff AS (
    SELECT DATE_SUB(MAX(order_date), INTERVAL 2 MONTH) AS cutoff_date
    FROM orders
)

SELECT 
    ss.seller_id,
    ss.last_sale_date,
    ss.total_sales
FROM seller_sales ss
CROSS JOIN cutoff c
WHERE ss.last_sale_date < c.cutoff_date
ORDER BY ss.last_sale_date;


/*
16. IDENTIFY customers into returning or new
if the customer has done more than 5 return categorize them as returning otherwise new
Challenge: List customers id, name, total orders, total returns
*/
WITH customer_summary AS (
    SELECT 
        customer_id,
        COUNT(*) AS total_orders,
        SUM(CASE WHEN order_status = 'Returned' THEN 1 ELSE 0 END) AS total_returns
    FROM orders
    GROUP BY customer_id
)

SELECT 
    cs.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    cs.total_orders,
    cs.total_returns,
    CASE 
        WHEN cs.total_returns > 5 THEN 'returning' 
        ELSE 'new' 
    END AS customer_category
FROM customer_summary cs
JOIN customers c
    ON cs.customer_id = c.customer_id
ORDER BY cs.total_returns DESC;


/*
17. Top 5 Customers by Orders in Each State
Identify the top 5 customers with the highest number of orders for each state. 
Challenge: Include the number of orders and total sales for each customer.
*/
WITH ranked_customers AS (
    SELECT
        c.customer_id,
        c.full_name,
        c.state,
        COUNT(*) AS total_orders,
        ROUND(SUM(oi.total_sales), 2) AS total_sales,
        DENSE_RANK() OVER (
            PARTITION BY c.state 
            ORDER BY COUNT(*) DESC, SUM(oi.total_sales) DESC
        ) AS state_rank
    FROM order_items oi
    JOIN orders o ON oi.order_id = o.order_id
    JOIN customers c ON o.customer_id = c.customer_id
    GROUP BY c.customer_id, c.full_name, c.state
)
SELECT *
FROM ranked_customers
WHERE state_rank <= 5
ORDER BY state, state_rank;



/*
18. Top 10 product with highest decreasing revenue ratio compare to last year (2022) and current_year (2023)
Challenge: Return product_id, product name, category_name, 2022 revenue and 2023 revenue decrease ratio at end Round the res Note: Decrease ratio = cr-ls/ls 100 ts = current_year ls last year)
*/
WITH revenue_by_year AS (
    SELECT 
        p.product_id,
        p.product_name,
        c.category_name,
        YEAR(o.order_date) AS order_year,
        SUM(oi.total_sales) AS total_revenue
    FROM order_items oi
    JOIN orders o 
        ON oi.order_id = o.order_id
    JOIN products p 
        ON oi.product_id = p.product_id
    JOIN categories c 
        ON p.category_id = c.category_id
    GROUP BY p.product_id, p.product_name, c.category_name, YEAR(o.order_date)
),
rev_compare AS (
    SELECT 
        r22.product_id,
        r22.product_name,
        r22.category_name,
        r22.total_revenue AS revenue_2022,
        r23.total_revenue AS revenue_2023,
        ROUND(((r23.total_revenue - r22.total_revenue) / r22.total_revenue) * 100, 2) AS decrease_ratio
    FROM revenue_by_year r22
    JOIN revenue_by_year r23
        ON r22.product_id = r23.product_id
       AND r22.order_year = 2022
       AND r23.order_year = 2023
)
SELECT 
    product_id,
    product_name,
    category_name,
    revenue_2022,
    revenue_2023,
    decrease_ratio
FROM rev_compare
WHERE decrease_ratio < 0   -- ensures we only show decreasing products
ORDER BY decrease_ratio ASC   -- most decreased first (negative biggest)
LIMIT 10;

